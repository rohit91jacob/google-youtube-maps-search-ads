"""Write docs/data_dictionary.md from the warehouse schema and the dbt YAML descriptions.

uv run geco fixtures-run --data-dir data/fixtures
GECO_DATA_DIR=data/fixtures uv run python scripts/generate_data_dictionary.py
"""

from __future__ import annotations

from pathlib import Path

import yaml

from geco.config import Settings
from geco.warehouse import connect

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "data_dictionary.md"

HEADER = """# Data dictionary

Generated by `scripts/generate_data_dictionary.py` from the warehouse schema (DuckDB types; the
BigQuery types are the obvious equivalents: VARCHAR -> STRING, BIGINT -> INT64, DOUBLE -> FLOAT64,
TIMESTAMP WITH TIME ZONE -> TIMESTAMP) and the dbt model descriptions. Hand-written definitions come
first.

## Definitions

| Term | Definition |
|---|---|
| Poll | One fetch of one Trends geo feed (or one YouTube channel feed). `polled_at` is the UTC fetch time. |
| Trending term | An item of Google Trends' trending-now RSS for a geo. `term_key` = casefolded, whitespace-normalised term, used to match a term across polls. |
| Churn rate | For a poll with a predecessor: terms not on the previous poll's list / terms on this list. 1.0 = complete turnover. |
| Observed hours | Hours between the first and the last poll that saw a term. A lower bound on how long it trended; resolution = the polling interval. |
| Completed term | A term neither on the geo's first poll (left-censored) nor on its latest poll (right-censored, `still_trending`). |
| Trend event | `entered` (on this poll, not the previous one) or `exited` (on the previous poll, not this one), published to Pub/Sub topic `trends-events` with a deterministic `event_id`. |
| Spend (political ads) | Amount Google reports an advertiser spent on election ads, in the report region's currency, rounded by Google to 100 units. Weeks run Sunday to Saturday (`week_start_date` is the Sunday). Zero-spend rows are dropped. |
| Report region | The region whose currency the spend is reported in (`ref_ads_currencies`): US = USD, IN = INR, EU = EUR and seven other EU currencies, etc. |
| Netflix week | Monday to Sunday; `week_end_date` is the Sunday (Netflix labels weeks this way). |
| Views (Netflix) | Hours viewed / runtime, as published by Netflix (from June 2023; null before). Not comparable to YouTube view counts. |
| Language (Netflix) | From Netflix's list: `english` or `non_english` (the four global lists are Films/TV x English/Non-English). |
| City box | A square of side 2 x `GECO_OSM_BOX_HALF_SIZE_KM` (10 km by default) centred on a fixed point per city (`geco.sources.osm.CITIES`). Area is computed exactly on a sphere (~100 km2). The box includes water and parks. |
| Amenity count | Overpass `out count` of nodes + ways + relations tagged `amenity=<value>` intersecting the box. |
| Upload gap | Hours between consecutive uploads of a channel among all uploads ever seen in its RSS feed. |

"""


def descriptions() -> tuple[dict[str, str], dict[tuple[str, str], str]]:
    models, columns = {}, {}
    paths = [*(ROOT / "dbt" / "models").rglob("*.yml"), *(ROOT / "dbt" / "seeds").rglob("*.yml")]
    for path in paths:
        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        for section in ("models", "seeds"):
            entries = doc.get(section) if isinstance(doc.get(section), list) else []
            for model in entries:
                models[model["name"]] = " ".join(str(model.get("description", "")).split())
                for col in model.get("columns", []) or []:
                    if col.get("description"):
                        columns[(model["name"], col["name"])] = " ".join(col["description"].split())
        for source in doc.get("sources") if isinstance(doc.get("sources"), list) else []:
            for table in source.get("tables", []) or []:
                models[table["name"]] = " ".join(str(table.get("description", "")).split())
    return models, columns


def main() -> None:
    settings = Settings()
    models, columns = descriptions()
    parts = [HEADER]
    with connect(settings.resolved_warehouse_path) as con:
        for schema, title in (
            ("raw", "Raw (parquet in the lake; BigQuery external tables)"),
            ("staging", "Staging (dbt views)"),
            ("intermediate", "Intermediate (dbt views)"),
            ("marts", "Marts (dbt tables)"),
        ):
            parts.append(f"## {title}\n")
            tables = [
                r[0]
                for r in con.execute(
                    "select table_name from information_schema.tables where table_schema = ? order by 1",
                    [schema],
                ).fetchall()
            ]
            for table in tables:
                parts.append(f"### `{schema}.{table}`\n")
                if models.get(table):
                    parts.append(models[table] + "\n")
                parts.append("| Column | Type | Description |\n|---|---|---|")
                for name, dtype in con.execute(
                    "select column_name, data_type from information_schema.columns "
                    "where table_schema = ? and table_name = ? order by ordinal_position",
                    [schema, table],
                ).fetchall():
                    parts.append(f"| `{name}` | {dtype} | {columns.get((table, name), '')} |")
                parts.append("")
    OUT.write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
